using Haseb.Api.Data;
using Haseb.Api.Models;
using Microsoft.EntityFrameworkCore;

var builder = WebApplication.CreateBuilder(args);
builder.Services.AddEndpointsApiExplorer();
builder.Services.AddSwaggerGen();

var connectionString = builder.Configuration.GetConnectionString("Default")
    ?? "Host=localhost;Port=5432;Database=haseb;Username=haseb;Password=ChangeThisStrongPassword";

builder.Services.AddDbContext<HasebDbContext>(options =>
    options.UseNpgsql(connectionString));

var app = builder.Build();

app.UseSwagger();
app.UseSwaggerUI();

using (var scope = app.Services.CreateScope())
{
    var db = scope.ServiceProvider.GetRequiredService<HasebDbContext>();
    await db.Database.EnsureCreatedAsync();

    // EnsureCreated برای دیتابیس‌های قبلی جدول جدید نمی‌سازد؛
    // این دستورات فقط جدول‌های مفقود را اضافه می‌کنند و داده‌های قبلی را حذف نمی‌کنند.
    await db.Database.ExecuteSqlRawAsync("""
        CREATE TABLE IF NOT EXISTS "Inventories" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "ProductId" integer NOT NULL UNIQUE REFERENCES "Products"("Id") ON DELETE CASCADE,
            "Quantity" numeric(18,3) NOT NULL DEFAULT 0,
            "MinimumQuantity" numeric(18,3) NOT NULL DEFAULT 0,
            "UpdatedAt" timestamp with time zone NOT NULL DEFAULT NOW()
        );
        """);

    await db.Database.ExecuteSqlRawAsync("""
        CREATE TABLE IF NOT EXISTS "StockMovements" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "ProductId" integer NOT NULL REFERENCES "Products"("Id") ON DELETE CASCADE,
            "Type" varchar(20) NOT NULL,
            "Quantity" numeric(18,3) NOT NULL,
            "BalanceAfter" numeric(18,3) NOT NULL,
            "Description" varchar(500),
            "CreatedAt" timestamp with time zone NOT NULL DEFAULT NOW()
        );
        """);

    await db.Database.ExecuteSqlRawAsync("""
        CREATE INDEX IF NOT EXISTS "IX_StockMovements_ProductId_CreatedAt"
        ON "StockMovements" ("ProductId", "CreatedAt");
        """);
}

app.MapGet("/health", () => Results.Ok(new { status = "ok", service = "haseb-api" }));
app.MapGet("/api/v1", () => Results.Ok(new { name = "حاسب", version = "0.2", modules = new[] { "products", "inventory" } }));

// کالاها
app.MapGet("/api/v1/products", async (HasebDbContext db) =>
    Results.Ok(await db.Products.AsNoTracking().OrderBy(p => p.Id).ToListAsync()));

app.MapGet("/api/v1/products/{id:int}", async (int id, HasebDbContext db) =>
{
    var product = await db.Products.FindAsync(id);
    return product is null ? Results.NotFound() : Results.Ok(product);
});

app.MapPost("/api/v1/products", async (ProductInput input, HasebDbContext db) =>
{
    if (string.IsNullOrWhiteSpace(input.Code) || string.IsNullOrWhiteSpace(input.Name) || input.Price < 0)
        return Results.BadRequest(new { error = "کد، نام و قیمت معتبر الزامی است." });

    if (await db.Products.AnyAsync(p => p.Code == input.Code))
        return Results.Conflict(new { error = "کد کالا تکراری است." });

    var product = new Product
    {
        Code = input.Code.Trim(),
        Name = input.Name.Trim(),
        Category = input.Category ?? "",
        Unit = input.Unit ?? "عدد",
        Price = input.Price,
        IsActive = input.IsActive
    };

    db.Products.Add(product);
    await db.SaveChangesAsync();
    return Results.Created($"/api/v1/products/{product.Id}", product);
});

app.MapPut("/api/v1/products/{id:int}", async (int id, ProductInput input, HasebDbContext db) =>
{
    var product = await db.Products.FindAsync(id);
    if (product is null) return Results.NotFound();
    if (string.IsNullOrWhiteSpace(input.Code) || string.IsNullOrWhiteSpace(input.Name) || input.Price < 0)
        return Results.BadRequest(new { error = "اطلاعات کالا معتبر نیست." });

    if (await db.Products.AnyAsync(p => p.Code == input.Code && p.Id != id))
        return Results.Conflict(new { error = "کد کالا تکراری است." });

    product.Code = input.Code.Trim();
    product.Name = input.Name.Trim();
    product.Category = input.Category ?? "";
    product.Unit = input.Unit ?? "عدد";
    product.Price = input.Price;
    product.IsActive = input.IsActive;
    await db.SaveChangesAsync();
    return Results.Ok(product);
});

app.MapDelete("/api/v1/products/{id:int}", async (int id, HasebDbContext db) =>
{
    var product = await db.Products.FindAsync(id);
    if (product is null) return Results.NotFound();
    db.Products.Remove(product);
    await db.SaveChangesAsync();
    return Results.NoContent();
});

// نمای موجودی تمام کالاها
app.MapGet("/api/v1/inventory", async (HasebDbContext db) =>
{
    var result = await db.Products.AsNoTracking()
        .Where(p => p.IsActive)
        .Select(p => new
        {
            productId = p.Id,
            code = p.Code,
            name = p.Name,
            category = p.Category,
            unit = p.Unit,
            quantity = db.Inventories.Where(i => i.ProductId == p.Id)
                .Select(i => (decimal?)i.Quantity).FirstOrDefault() ?? 0,
            minimumQuantity = db.Inventories.Where(i => i.ProductId == p.Id)
                .Select(i => (decimal?)i.MinimumQuantity).FirstOrDefault() ?? 0
        })
        .ToListAsync();

    return Results.Ok(result.Select(x => new
    {
        x.productId, x.code, x.name, x.category, x.unit,
        x.quantity, x.minimumQuantity,
        isLowStock = x.quantity <= x.minimumQuantity
    }));
});

// تنظیم حداقل موجودی
app.MapPut("/api/v1/inventory/{productId:int}/minimum", async (
    int productId, MinimumStockInput input, HasebDbContext db) =>
{
    if (input.MinimumQuantity < 0)
        return Results.BadRequest(new { error = "حداقل موجودی نمی‌تواند منفی باشد." });

    if (!await db.Products.AnyAsync(p => p.Id == productId))
        return Results.NotFound(new { error = "کالا پیدا نشد." });

    var inventory = await db.Inventories.SingleOrDefaultAsync(i => i.ProductId == productId);
    if (inventory is null)
    {
        inventory = new Inventory { ProductId = productId, Quantity = 0 };
        db.Inventories.Add(inventory);
    }

    inventory.MinimumQuantity = input.MinimumQuantity;
    inventory.UpdatedAt = DateTime.UtcNow;
    await db.SaveChangesAsync();

    return Results.Ok(new { inventory.ProductId, inventory.Quantity, inventory.MinimumQuantity });
});

// ثبت ورود یا خروج کالا
app.MapPost("/api/v1/inventory/movements", async (
    MovementInput input, HasebDbContext db) =>
{
    if (input.ProductId <= 0 || input.Quantity <= 0)
        return Results.BadRequest(new { error = "شناسه کالا و مقدار باید معتبر و مثبت باشند." });

    var type = input.Type?.Trim().ToLowerInvariant();
    if (type is not ("in" or "out"))
        return Results.BadRequest(new { error = "نوع گردش باید in یا out باشد." });

    await using var transaction = await db.Database.BeginTransactionAsync();

    var product = await db.Products.SingleOrDefaultAsync(p => p.Id == input.ProductId);
    if (product is null)
        return Results.NotFound(new { error = "کالا پیدا نشد." });

    var inventory = await db.Inventories.SingleOrDefaultAsync(i => i.ProductId == input.ProductId);
    if (inventory is null)
    {
        inventory = new Inventory { ProductId = input.ProductId, Quantity = 0 };
        db.Inventories.Add(inventory);
        await db.SaveChangesAsync();
    }

    var newBalance = type == "in"
        ? inventory.Quantity + input.Quantity
        : inventory.Quantity - input.Quantity;

    if (newBalance < 0)
        return Results.BadRequest(new { error = "موجودی کافی نیست.", available = inventory.Quantity });

    inventory.Quantity = newBalance;
    inventory.UpdatedAt = DateTime.UtcNow;

    var movement = new StockMovement
    {
        ProductId = input.ProductId,
        Type = type,
        Quantity = input.Quantity,
        BalanceAfter = newBalance,
        Description = input.Description?.Trim(),
        CreatedAt = DateTime.UtcNow
    };

    db.StockMovements.Add(movement);
    await db.SaveChangesAsync();
    await transaction.CommitAsync();

    return Results.Created($"/api/v1/inventory/movements/{movement.Id}", new
    {
        movement.Id, movement.ProductId, movement.Type,
        movement.Quantity, movement.BalanceAfter,
        movement.Description, movement.CreatedAt,
        productName = product.Name,
        unit = product.Unit
    });
});

// تاریخچه گردش یک کالا
app.MapGet("/api/v1/inventory/{productId:int}/movements", async (
    int productId, HasebDbContext db) =>
{
    if (!await db.Products.AnyAsync(p => p.Id == productId))
        return Results.NotFound();

    var movements = await db.StockMovements.AsNoTracking()
        .Where(m => m.ProductId == productId)
        .OrderByDescending(m => m.CreatedAt)
        .Take(200)
        .Select(m => new
        {
            m.Id, m.ProductId, m.Type, m.Quantity,
            m.BalanceAfter, m.Description, m.CreatedAt
        })
        .ToListAsync();

    return Results.Ok(movements);
});

// هشدار کالاهای زیر حداقل موجودی
app.MapGet("/api/v1/inventory/low-stock", async (HasebDbContext db) =>
{
    var result = await db.Inventories.AsNoTracking()
        .Include(i => i.Product)
        .Where(i => i.Product != null && i.Quantity <= i.MinimumQuantity)
        .OrderBy(i => i.Quantity)
        .Select(i => new
        {
            i.ProductId,
            productName = i.Product!.Name,
            code = i.Product!.Code,
            i.Quantity,
            i.MinimumQuantity,
            unit = i.Product!.Unit
        })
        .ToListAsync();

    return Results.Ok(result);
});

app.Run();

record ProductInput(string Code, string Name, string? Category, string? Unit, decimal Price, bool IsActive = true);
record MinimumStockInput(decimal MinimumQuantity);
record MovementInput(int ProductId, string Type, decimal Quantity, string? Description);
